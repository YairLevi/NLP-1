"""Answer the unigram questions (part B, Q1-Q7) from the files written by count.py.

Usage:
    python analyze.py [out dir] [results file]
Defaults: out/  and  results.md  (relative to this script).

Expects, for each language L in (english, hebrew):
    <out>/L.counts.tsv, <out>/L.half.tsv, <out>/L.meta.json
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANGS = ("english", "hebrew")
RANKS = (100, 1_000, 10_000)
EXACT = (1, 2, 3, 5)
AT_LEAST = (10, 100, 1_000, 10_000)
N_EXAMPLES = 10


def load_counts(path):
    """Return [(type, count), ...] in file order (most frequent first)."""
    items = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            tok, c = line.rstrip("\n").split("\t")
            items.append((tok, int(c)))
    return items


def analyze(out_dir, lang):
    full = load_counts(out_dir / f"{lang}.counts.tsv")
    half_types = {t for t, _ in load_counts(out_dir / f"{lang}.half.tsv")}
    meta = json.loads((out_dir / f"{lang}.meta.json").read_text())

    # A type missing from the first half has ALL its occurrences in the
    # second half, so its full-file count is its second-half count.
    new_in_second = [(t, c) for t, c in full if t not in half_types]
    freq = [c for _, c in full]
    return {
        "tokens": meta["tokens"],
        "types": len(full),
        "half_tokens": meta["half"],
        "half_types": len(half_types),
        "new_types": len(new_in_second),
        "new_bands": {
            # (label, lower bound exclusive, upper bound inclusive)
            label: [(t, c) for t, c in new_in_second if lo < c <= hi]
            for label, lo, hi in (("3-5", 2, 5), ("6-10", 5, 10), (">10", 10, float("inf")))
        },
        "new_gt": {k: sum(1 for _, c in new_in_second if c > k) for k in (2, 5, 10)},
        "top50": full[:50],
        "ranks": {r: full[r - 1] if r <= len(full) else None for r in RANKS},
        "exact": {k: sum(1 for c in freq if c == k) for k in EXACT},
        "at_least": {k: sum(1 for c in freq if c >= k) for k in AT_LEAST},
    }


SCRIPT = {
    "english": lambda ch: "a" <= ch.lower() <= "z",
    "hebrew": lambda ch: "א" <= ch <= "ת",
}


def is_wordlike(tok, lang):
    """All letters are in the language's own script, and there are no digits."""
    in_script = SCRIPT[lang]
    return (any(in_script(ch) for ch in tok)
            and all(in_script(ch) for ch in tok if ch.isalpha())
            and not any(ch.isdigit() for ch in tok))


def fmt_examples(items, lang):
    """Show word-like examples in the language's script: ties in count are
    sorted alphabetically, which would otherwise fill the list with numbers
    (and, for Hebrew, with Latin-script words)."""
    if not items:
        return "none"
    words = [x for x in items if is_wordlike(x[0], lang)]
    digits = sum(1 for t, _ in items if any(ch.isdigit() for ch in t))
    shown = ", ".join(f"`{t}` ({c})" for t, c in words[:N_EXAMPLES])
    return f"{shown} — {len(items):,} types, {100 * digits / len(items):.0f}% contain digits"


def report(res):
    E, H = res["english"], res["hebrew"]
    out = ["# Unigram results", "",
           "Generated by `analyze.py` from the counts written by `count.py`.",
           "Explanations of the phenomena are in [`unigrams.md`](unigrams.md).", ""]

    out += ["## Q1-Q3: tokens, types, ratio", "",
            "| | English | Hebrew |", "|---|---:|---:|",
            f"| tokens | {E['tokens']:,} | {H['tokens']:,} |",
            f"| types | {E['types']:,} | {H['types']:,} |",
            f"| tokens / types | {E['tokens'] / E['types']:.2f} | {H['tokens'] / H['types']:.2f} |", ""]

    out += ["## Q4: first half vs. whole file", "",
            "| | English | Hebrew |", "|---|---:|---:|",
            f"| tokens in first half (N/2) | {E['half_tokens']:,} | {H['half_tokens']:,} |",
            f"| types in first half | {E['half_types']:,} | {H['half_types']:,} |",
            f"| types added by the second half | {E['new_types']:,} | {H['new_types']:,} |"]
    for k in (2, 5, 10):
        out.append(f"| new types appearing > {k} times in second half "
                   f"| {E['new_gt'][k]:,} | {H['new_gt'][k]:,} |")
    out.append("")
    for lang, r in res.items():
        out.append(f"**{lang.capitalize()}**, examples of types absent from the first half "
                   f"(count in the second half, most frequent first):")
        out.append("")
        for band in ("3-5", "6-10", ">10"):
            out.append(f"- {band} times: {fmt_examples(r['new_bands'][band], lang)}")
        out.append("")

    out += ["## Q5: top 50 token-types", "",
            "| rank | English | count | Hebrew | count |", "|---:|---|---:|---|---:|"]
    for i, ((et, ec), (ht, hc)) in enumerate(zip(E["top50"], H["top50"]), 1):
        out.append(f"| {i} | {et} | {ec:,} | {ht} | {hc:,} |")
    out.append("")

    out += ["## Q6: words at given frequency ranks", "",
            "| rank | English | count | Hebrew | count |", "|---:|---|---:|---|---:|"]
    for r in RANKS:
        (et, ec), (ht, hc) = E["ranks"][r], H["ranks"][r]
        out.append(f"| {r:,} | {et} | {ec:,} | {ht} | {hc:,} |")
    out += ["", "Ties in count are broken alphabetically.", ""]

    out += ["## Q7: frequency-of-frequencies", "",
            "| number of types that appear | English | Hebrew |", "|---|---:|---:|"]
    for k in EXACT:
        out.append(f"| exactly {k} time{'s' if k > 1 else ''} | {E['exact'][k]:,} | {H['exact'][k]:,} |")
    for k in AT_LEAST:
        out.append(f"| {k:,} times or more | {E['at_least'][k]:,} | {H['at_least'][k]:,} |")
    out.append("")
    return "\n".join(out)


def main():
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "out"
    dest = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "results.md"
    res = {lang: analyze(out_dir, lang) for lang in LANGS}
    dest.write_text(report(res), encoding="utf-8")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
